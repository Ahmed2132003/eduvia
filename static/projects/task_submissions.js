function toggleMenu() {
    const menu = document.querySelector('.menu');
    menu.classList.toggle('active');
}

function toggleDarkMode() {
    const body = document.body;
    const toggleIcon = document.querySelector('.dark-mode-toggle i');
    body.classList.toggle('dark-mode');
    
    if (body.classList.contains('dark-mode')) {
        toggleIcon.classList.remove('fa-moon');
        toggleIcon.classList.add('fa-sun');
        localStorage.setItem('theme', 'dark');
    } else {
        toggleIcon.classList.remove('fa-sun');
        toggleIcon.classList.add('fa-moon');
        localStorage.setItem('theme', 'light');
    }
}

function toggleLanguage() {
    const htmlRoot = document.getElementById('html-root');
    const currentLang = htmlRoot.getAttribute('lang') || 'en';
    const newLang = currentLang === 'en' ? 'ar' : 'en';
    
    // Ensure taskTitle and projectTitle are defined
    const taskTitle = window.taskTitle || 'Task';
    const projectTitle = window.projectTitle || 'Project';
    
    htmlRoot.setAttribute('lang', newLang);
    htmlRoot.setAttribute('dir', newLang === 'ar' ? 'rtl' : 'ltr');
    
    document.querySelectorAll('[data-translate]').forEach(element => {
        const key = element.getAttribute('data-translate');
        let text = translations[newLang][key];
        if (text) {
            text = text.replace('{taskTitle}', taskTitle).replace('{projectTitle}', projectTitle);
            if (element.tagName.toLowerCase() === 'meta') {
                if (element.getAttribute('name') === 'description' || element.getAttribute('name') === 'keywords' || element.getAttribute('name')?.startsWith('twitter:')) {
                    element.setAttribute('content', text);
                } else if (element.getAttribute('property')?.startsWith('og:')) {
                    element.setAttribute('content', text);
                }
            } else if (key === 'no-rooms') {
                const link = element.querySelector('a');
                if (link) {
                    element.innerHTML = translations[newLang]["no-rooms-text"] + ' <a href="' + link.getAttribute('href') + '" data-translate="create-room-link">' + translations[newLang]["create-room-link"] + '</a>.';
                }
            } else {
                element.textContent = text;
            }
        }
    });

    document.title = translations[newLang]["page-title"].replace('{taskTitle}', taskTitle);
    
    const schema = document.getElementById('schema-markup');
    if (schema) {
        const schemaData = JSON.parse(schema.textContent);
        schemaData[1].name = translations[newLang]["schema-name"].replace('{taskTitle}', taskTitle);
        schemaData[1].description = translations[newLang]["schema-desc"].replace('{taskTitle}', taskTitle).replace('{projectTitle}', projectTitle);
        schemaData[1].inLanguage = newLang;
        schemaData[0].name = translations[newLang]["schema-organization"];
        schemaData[2].itemListElement[0].name = translations[newLang]["schema-breadcrumb-home"];
        schemaData[2].itemListElement[1].name = translations[newLang]["schema-breadcrumb-projects"];
        schemaData[2].itemListElement[2].name = translations[newLang]["schema-breadcrumb-task"].replace('{taskTitle}', taskTitle);
        schema.textContent = JSON.stringify(schemaData, null, 2);
    }
    
    localStorage.setItem('language', newLang);
}

