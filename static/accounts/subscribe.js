function toggleMenu() {
    const menu = document.querySelector('.menu');
    menu.classList.toggle('active');
    console.log('Menu toggled:', menu.classList.contains('active'));
}

function toggleDarkMode() {
    const body = document.body;
    const toggleIcon = document.querySelector('.dark-mode-toggle i');
    body.classList.toggle('dark-mode');
    
    if (body.classList.contains('dark-mode')) {
        toggleIcon.classList.remove('fa-moon');
        toggleIcon.classList.add('fa-sun');
        localStorage.setItem('theme', 'dark');
    } else {
        toggleIcon.classList.remove('fa-sun');
        toggleIcon.classList.add('fa-moon');
        localStorage.setItem('theme', 'light');
    }
}

function toggleLanguage() {
    const htmlRoot = document.getElementById('html-root');
    const currentLang = htmlRoot.getAttribute('lang');
    const newLang = currentLang === 'en' ? 'ar' : 'en';
    
    htmlRoot.setAttribute('lang', newLang);
    htmlRoot.setAttribute('dir', newLang === 'ar' ? 'rtl' : 'ltr');
    
    document.querySelectorAll('[data-translate]').forEach(element => {
        const key = element.getAttribute('data-translate');
        if (key.endsWith('-features') || key.endsWith('-limitations')) {
            const items = translations[newLang][key].split('\n');
            const ul = element;
            ul.innerHTML = '';
            items.forEach(item => {
                const li = document.createElement('li');
                li.textContent = item;
                ul.appendChild(li);
            });
        } else {
            element.textContent = translations[newLang][key];
            if (element.tagName.toLowerCase() === 'input' && element.getAttribute('type') === 'text') {
                element.setAttribute('placeholder', translations[newLang][key]);
            }
        }
    });

    document.title = translations[newLang]["title"];
    localStorage.setItem('language', newLang);
}

